"""Generate docs/RESULTS.md from the season artifacts (``f1line report``)."""

from __future__ import annotations

import json
from dataclasses import replace
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from f1line.vehicle.calibrate import load_theta
from f1line.vehicle.qss import menger_curvature, simulate_lap


def _sensitivity(cfg: dict[str, Any], circuit: str, params: Any, pct: float) -> dict[str, float]:
    """Lap-time change [%] on the stored optimal line for +pct % in mu, c_l, p_spec."""
    d = Path(cfg["paths"]["season_dir"]) / circuit
    tr = pd.read_parquet(d / "track.parquet")
    ln = pd.read_parquet(d / "lines.parquet")
    a = ln["alpha_mintime"].to_numpy()
    x = tr["x"].to_numpy() + a * tr["nx"].to_numpy()
    y = tr["y"].to_numpy() + a * tr["ny"].to_numpy()
    k = menger_curvature(x, y)
    ds = np.hypot(np.roll(x, -1) - x, np.roll(y, -1) - y)
    base = simulate_lap(k, ds, params).lap_time_s
    f = 1 + pct / 100
    out = {}
    for name in ("mu", "c_l", "p_spec"):
        p = replace(params, **{name: getattr(params, name) * f})
        out[name] = (simulate_lap(k, ds, p).lap_time_s / base - 1) * 100
    return out


def write_results(cfg: dict[str, Any], output: Path) -> Path:
    """Write the results markdown; returns its path."""
    year = int(cfg["season"]["year"])
    season_dir = Path(cfg["paths"]["season_dir"])
    theta_path = Path(cfg["paths"]["models_dir"]) / f"theta_{year}.json"
    table_path = Path("reports") / f"season_{year}.csv"
    if not theta_path.exists() or not table_path.exists():
        raise FileNotFoundError("Run `f1line build-season` first")
    theta = json.loads(theta_path.read_text())
    diag = theta["diagnostics"]
    params = load_theta(theta_path)
    df = pd.read_csv(table_path)
    pct = float(cfg.get("validation", {}).get("sensitivity_pct", 5))

    raced = df[df["data_year"] == year]
    held = raced["gap_loco_pct"].dropna()
    sens = []
    for c in df["circuit"]:
        if (season_dir / c / "lines.parquet").exists():
            sens.append({"circuit": c, **_sensitivity(cfg, c, params, pct)})
    sens_df = pd.DataFrame(sens)

    mono = df[(df["min_time_s"] <= df["min_curv_s"] + 1e-6)
              & (df["min_curv_s"] <= df["centerline_s"] + 1e-6)]
    fmt = lambda v: f"{v:.5g}"  # noqa: E731
    lines = [
        f"# Results – {year} season",
        "",
        f"Generated by `f1line report` on {datetime.now():%Y-%m-%d %H:%M}. "
        "All numbers come from `reports/season_{year}.csv` and `models/theta_{year}.json`."
        .replace("{year}", str(year)),
        "",
        "## Summary",
        "",
        f"- Races processed: **{len(df)}** completed rounds of {year}, each compared with its "
        "real qualifying pole lap.",
        f"- Geometry sources: {df['geometry'].value_counts().to_dict()}.",
        "- Grip utilization γ by official circuit type: "
        + ", ".join(f"{g} **{v:.3f}**" for g, v in
                    (diag.get("grip_utilization_by_group") or
                     {"all": diag["grip_utilization"]}).items()) + ".",
        f"- **Pole forecast** (physics model correlated to that weekend's practice pace, no "
        f"qualifying data): mean |gap| **{df['gap_pct'].abs().mean():.2f} %**, median "
        f"**{df['gap_pct'].abs().median():.2f} %**, worst {df['gap_pct'].abs().max():.2f} %.",
        f"- **Physics only** (grip by circuit type, fitted leaving the race out): mean |gap| "
        f"**{held.abs().mean():.2f} %**, median {held.abs().median():.2f} %, range "
        f"{held.min():+.2f} … {held.max():+.2f} %." if len(held) else "- No held-out results.",
        f"- Monotonic improvement (min-time ≤ min-curvature ≤ centerline): "
        f"**{len(mono)}/{len(df)}** circuits.",
        f"- Optimizer: {df['solver'].value_counts().to_dict()}; NLP vs independent QSS lap "
        f"time differ by at most {df['nlp_qss_diff_pct'].max():.2f} %.",
        "",
        "## Calibrated car",
        "",
        "Season car θ, fitted on every 2026 qualifying lap:",
        "",
        "| Parameter | Season car θ | Std. error |",
        "|---|---|---|",
    ]
    for k, v in diag["base_params"].items():
        lines.append(f"| {k} | {fmt(v)} | {fmt(diag['stderr'].get(k, float('nan')))} |")
    lines += [
        "",
        f"Parameters at a bound after the telemetry fit: {diag.get('params_at_bound') or 'none'}.",
        "",
    ]
    if diag.get("setup"):
        lines += [
            "Weekend setup: downforce c_L and drag c_D refitted on each weekend's last session "
            "before qualifying (practice or sprint qualifying); grip factor γ by official "
            "circuit type.",
            "",
            "| Circuit | Official type | Setup source | c_L | c_D | γ | held-out γ |",
            "|---|---|---|---|---|---|---|",
        ]
        for c, s in diag["setup"].items():
            sp = diag["setup_params"][c]
            g = diag["grip_utilization_by_group"][diag["grip_group"][c]]
            lines.append(
                f"| {c} | {diag['circuit_type'].get(c, '?')} | {s['source']} | {fmt(sp['c_l'])} "
                f"| {fmt(sp['c_d'])} | {g:.3f} | {diag['grip_utilization_loco'][c]:.3f} |"
            )
        lines.append("")
    lines += [
        "## Per-circuit results",
        "",
        "Lap times in seconds. *gap* = model forecast (correlated to the weekend's practice) vs "
        "real pole; *gap_loco* = physics only, grip fitted without that circuit; *replay* = model "
        "on the pole driver's own reconstructed line.",
        "",
        df.to_markdown(index=False, floatfmt=".2f"),
        "",
        f"## Sensitivity (+{pct:.0f} % parameter → lap time change, optimal line fixed)",
        "",
        sens_df.to_markdown(index=False, floatfmt="+.2f") if len(sens_df) else "n/a",
        "",
        "## Analysis and limitations",
        "",
        "- **Grip utilization.** Calibrating on the drivers' reconstructed lines over-estimates "
        "grip: at ~3.7 Hz the positions are up to 20 m apart, the reconstructed curvature is noisy, "
        "and the fit raises grip to recover the real lap time. Noise-free optimized lines then come "
        "out ~10 % faster than pole. A grip-utilization factor γ (scaling the tyre friction "
        "coefficients) is therefore fitted per official circuit type (OpenF1: street vs "
        "permanent/road) so that model optima match real poles on average; it also absorbs what "
        "a point mass cannot do (yaw/roll transients, walls, bumps). The held-out column is the "
        "honest prediction error.",
        "- **Practice correlation.** As teams correlate their simulator to Friday/Saturday "
        "running, the grip level of each weekend is tuned so the optimal lap equals the best "
        "pre-qualifying lap times the typical practice-to-pole ratio of the *other* races with the "
        "same session type (FP3 or sprint qualifying). The physics then decides the line, speeds "
        "and where time is won; the lap-time accuracy mostly comes from the practice pace.",
        "- **Weekend setup.** Downforce and drag are refitted per weekend on the last session "
        "before qualifying (practice or sprint qualifying), so wing level follows the circuit. "
        "Setup alone did not help (held-out mean |gap| 4.5 %), grip by circuit type alone gave "
        "3.0 %, both together 3.2 % mean and 2.8 % median with the worst case cut from 11.5 % to "
        "8.6 %.",
        "- **Replay error is large by construction** once γ < 1: the noisy reconstructed driver "
        "line is slower in the model than it is in reality.",
        "- **Min-curvature vs min-time.** The min-curvature line is several percent slower than "
        "the min-time line on most circuits: it spreads curvature evenly, while time is lost "
        "mostly in fast corners where the γ-limited grip binds.",
        "- **Outliers.** Melbourne (+8.6 %) and Miami (+3.8 %) are officially street circuits "
        "but are fast park/stadium layouts, so the street grip level (fitted mostly on Monaco, "
        "Baku, Singapore, Madring) is too low for them. Madring (−8 %) and Monaco (−6 %) have "
        "short, approximate geometry (drivers' mean line / OSM ~3 % under the official length). "
        "Monza (−6 %) is the lowest-downforce circuit, where the model's slipstream-free, "
        "energy-unlimited straights flatter it.",
        "- **2026 cars.** Active aero (straight-line mode) and the 50/50 power split with energy "
        "clipping on straights are not modelled; drag and power are effective values.",
        "- **Not modelled:** elevation, banking, kerbs beyond the car-centre bound, tyre state, "
        "wind, traffic, DRS/overtake mode.",
        f"- **Scope.** Only the {len(df)} rounds of {year} that have been run are included "
        "(`season.completed_only`); remaining rounds are added by re-running the pipeline after "
        "each qualifying session.",
        "- **Geometry.** TUM layouts are used only if the driven laps fit them (≥95 % of samples "
        "inside bounds + 1 m position tolerance); otherwise OpenStreetMap (nominal widths, widened "
        "to observed car positions). Madring has incomplete OSM data and uses the drivers' mean "
        "line (approximate).",
    ]
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return output
